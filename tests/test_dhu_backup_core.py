class CredentialOwnFixtureTests(unittest.TestCase):
    """The population this project can regenerate on its own, from its own rules.

    It is derived from the rules' OWN regexes rather than from a set of paths
    somebody chose, and each row records which rule GENERATED it and which rule
    FIRED. That is what proves every rule in the table is live, does what it
    says, and is not a mis-transcription that happens to be shadowed by another
    rule — a verdict-level population cannot see any of that.
    """

    @classmethod
    def setUpClass(cls):
        with open(OWN_FIXTURE_PATH) as handle:
            cls.fixture = json.load(handle)

    def test_every_rule_fires_on_at_least_one_of_its_own_probes(self):
        """A rule that never fires is dead code or a mis-transcription.

        `.git/credentials` was exactly this: `^credentials$` claimed the path
        first, so the tail rule could not fire and nothing in the suite could
        tell it apart from a live one.
        """
        fired = set()
        for row in self.fixture["rows"]:
            if row["fired"] == row["rule"]:
                fired.add(row["rule"])
        dead = sorted(r.id for r in credential_patterns.RULES if r.id not in fired)
        self.assertEqual(dead, [], "rules that never fired on their own probes:\n"
                                   + "\n".join(dead))

    def test_every_example_gets_the_verdict_its_rule_claims(self):
        wrong = []
        for row in self.fixture["rows"]:
            if row["source"] != "example":
                continue
            expected_refusal = row["expected"] == credential_patterns.REFUSE
            if row["refused"] != expected_refusal:
                wrong.append("%s: %s claimed %s, got %r"
                             % (row["rule"], row["relpath"], row["expected"], row["reason"]))
            elif expected_refusal and row["fired"] != row["rule"]:
                # Refused, but by a DIFFERENT rule. The example then proves
                # nothing about the rule that states it.
                wrong.append("%s: %s was refused by %s instead"
                             % (row["rule"], row["relpath"], row["fired"]))
        self.assertEqual(wrong, [], "\n".join(wrong))

    def test_the_fixture_describes_the_current_rule_set(self):
        # Otherwise "every rule fires" is a claim about the rules the fixture
        # happens to remember, not the rules the daemon runs.
        in_fixture = set(row["rule"] for row in self.fixture["rows"])
        self.assertEqual(sorted(in_fixture),
                         sorted(r.id for r in credential_patterns.RULES))
        self.assertEqual(self.fixture["rule_count"], len(credential_patterns.RULES))

    def test_every_recorded_verdict_still_holds(self):
        """Recompute, do not trust. A committed verdict is a snapshot.

        This is what turns the file from a record of what the predicate once did
        into an assertion about what it does now.
        """
        drifted = []
        for row in self.fixture["rows"]:
            match = dhu_backup_core.credential_match(row["relpath"])
            refused = match is not None
            fired = match.rule.id if match is not None else None
            if refused != row["refused"] or fired != row["fired"]:
                drifted.append("%s: recorded (%s, %s), now (%s, %s)"
                               % (row["relpath"], row["refused"], row["fired"],
                                  refused, fired))
        self.assertEqual(drifted, [], "\n".join(drifted))

    def test_the_population_is_not_trivially_small_or_all_admitted(self):
        rows = self.fixture["rows"]
        self.assertGreaterEqual(len(rows), 250)
        refused = [r for r in rows if r["refused"]]
        self.assertGreaterEqual(len(refused), 100)
        self.assertGreaterEqual(len(rows) - len(refused), 50)

    def test_the_fixture_is_not_stale(self):
        """Re-run the generator in --check mode; it changes nothing and exits 1
        if the committed file is not what it would write today."""
        result = subprocess.run(
            ["/usr/bin/python3", DERIVE_TOOL, "--check"],
            capture_output=True, text=True, cwd=REPO_ROOT)
        self.assertEqual(result.returncode, 0,
                         "rerun src/tools/derive-own-fixture.py\n"
                         + result.stdout + result.stderr)


