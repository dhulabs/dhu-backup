class FakeStat(object):
    """The four fields `classify_entry` reads, fabricated.

    Deliberately not an `os.stat_result`: the production caller passes the
    result of `os.fstat` on an already-open fd, and a test that built a real
    stat would need a real file — which is how a pure-function suite acquires a
    filesystem dependency.
    """

    def __init__(self, mode=stat.S_IFREG | 0o644, nlink=1, uid=OWNER_UID, size=100):
        self.st_mode = mode
        self.st_nlink = nlink
        self.st_uid = uid
        self.st_size = size


# ── classify_entry ────────────────────────────────────────────────────────────


class ClassifyEntryTests(unittest.TestCase):
    def test_accepts_a_plain_owner_owned_regular_file(self):
        verdict = classify_entry("notes.md", FakeStat(), "docs/notes.md", owner_uid=OWNER_UID)
        self.assertIsInstance(verdict, Copy)
        self.assertEqual(verdict.relpath, "docs/notes.md")
        self.assertEqual(verdict.size, 100)

    def test_refuses_a_hard_link(self):
        # `ln /etc/sudoers ./notes.md` succeeds as an unprivileged user (verified
        # on this machine), and a ROOT reader would then copy a file the agent
        # cannot itself read. nlink != 1 is the whole defence.
        verdict = classify_entry("notes.md", FakeStat(nlink=2), "notes.md", owner_uid=OWNER_UID)
        self.assertIsInstance(verdict, Refuse)
        self.assertIn("hardlink", verdict.reason)

    def test_refuses_a_symlink(self):
        st = FakeStat(mode=stat.S_IFLNK | 0o777)
        verdict = classify_entry("link", st, "link", owner_uid=OWNER_UID)
        self.assertEqual(verdict, Refuse("symlink"))

    def test_refuses_a_non_regular_file(self):
        for mode, label in [
            (stat.S_IFDIR | 0o755, "dir"),
            (stat.S_IFIFO | 0o644, "fifo"),
            (stat.S_IFSOCK | 0o644, "socket"),
            (stat.S_IFCHR | 0o644, "chardev"),
        ]:
            verdict = classify_entry("x", FakeStat(mode=mode), "x", owner_uid=OWNER_UID)
            self.assertEqual(verdict, Refuse("not-regular-file"), label)

    def test_refuses_a_file_owned_by_someone_else(self):
        verdict = classify_entry("x", FakeStat(uid=0), "x", owner_uid=OWNER_UID)
        self.assertIsInstance(verdict, Refuse)
        self.assertIn("wrong-owner", verdict.reason)

    def test_refuses_setuid_and_setgid(self):
        for bit in (stat.S_ISUID, stat.S_ISGID):
            st = FakeStat(mode=stat.S_IFREG | 0o755 | bit)
            self.assertEqual(
                classify_entry("x", st, "x", owner_uid=OWNER_UID),
                Refuse("setuid-or-setgid"),
            )

    def test_refuses_a_file_over_the_size_cap(self):
        st = FakeStat(size=dhu_backup_core.MAX_FILE_BYTES + 1)
        verdict = classify_entry("big.txt", st, "big.txt", owner_uid=OWNER_UID)
        self.assertIsInstance(verdict, Refuse)
        self.assertIn("too-large", verdict.reason)

    def test_accepts_a_file_exactly_at_the_size_cap(self):
        st = FakeStat(size=dhu_backup_core.MAX_FILE_BYTES)
        self.assertIsInstance(
            classify_entry("big.txt", st, "big.txt", owner_uid=OWNER_UID), Copy
        )

    def test_refuses_an_excluded_directory_anywhere_in_the_relpath(self):
        for relpath in [
            "node_modules/left-pad/index.md",
            "a/b/node_modules/x.md",
            ".git/config.txt",
            "lib/generated/prisma/client.md",
            "deploy/edge-node/bundles/x.md",
        ]:
            verdict = classify_entry(
                os.path.basename(relpath), FakeStat(), relpath, owner_uid=OWNER_UID
            )
            self.assertIsInstance(verdict, Refuse, relpath)
            self.assertTrue(verdict.reason.startswith("excluded-dir"), relpath)

    def test_refuses_an_excluded_extension(self):
        for name in ["model.gguf", "weights.safetensors", "dev.log", "clip.mp4", "SHOT.PNG"]:
            verdict = classify_entry(name, FakeStat(), "x/" + name, owner_uid=OWNER_UID)
            self.assertIsInstance(verdict, Refuse, name)
            self.assertTrue(verdict.reason.startswith("excluded-extension"), name)

    def test_captures_a_credential_path_and_routes_it_to_the_vault(self):
        """A credential file is CAPTURED, not refused — and never made readable.

        The first build refused it outright, which chose "the agent cannot read
        it" by making it unrecoverable for anyone. The split store (review C4b)
        gets both: `store/` is agent-readable and holds nothing the repo's own
        guards would refuse; `vault/` is root-only and holds the rest, so the
        owner can still recover a deleted `.env.local` with sudo.
        """
        for relpath in [".env.local", "deploy/edge-node/id_rsa", ".ssh/known_hosts"]:
            verdict = classify_entry(
                os.path.basename(relpath), FakeStat(), relpath, owner_uid=OWNER_UID
            )
            self.assertIsInstance(verdict, Copy, relpath)
            self.assertEqual(destination_for(relpath), "vault", relpath)
        for relpath in ["lib/db.ts", "docs/notes.md", ".env.local.example"]:
            self.assertEqual(destination_for(relpath), "store", relpath)

    def test_refuses_an_unsafe_relpath(self):
        for relpath in ["../escape.md", "/absolute.md", "a/../../b.md"]:
            self.assertEqual(
                classify_entry("x.md", FakeStat(), relpath, owner_uid=OWNER_UID),
                Refuse("unsafe-relpath"),
            )

    def test_every_refusal_carries_a_nonempty_reason(self):
        # No silent fallbacks: a refusal must never be indistinguishable from
        # "nothing was there".
        cases = [
            FakeStat(nlink=9),
            FakeStat(mode=stat.S_IFDIR | 0o755),
            FakeStat(uid=0),
            FakeStat(size=dhu_backup_core.MAX_FILE_BYTES + 1),
        ]
        for st in cases:
            verdict = classify_entry("x", st, "x", owner_uid=OWNER_UID)
            self.assertIsInstance(verdict, Refuse)
            self.assertTrue(verdict.reason and verdict.reason.strip())


# ── is_safe_relpath / store keys ──────────────────────────────────────────────


class RelpathTests(unittest.TestCase):
    def test_rejects_traversal_absolute_nul_and_empty(self):
        for bad in [
            "..",
            "../x",
            "a/../../b",
            "a/..",
            "/lead",
            "//lead",
            "a\x00b",
            "",
            "C:/windows/x",
            "\\\\server\\share",
        ]:
            self.assertFalse(is_safe_relpath(bad), bad)

    def test_accepts_ordinary_paths(self):
        for good in ["a.md", "a/b/c.md", "a/./b.md", "dot.dot/x", "..hidden/x", "a..b/c"]:
            self.assertTrue(is_safe_relpath(good), good)

    def test_rejects_non_strings(self):
        for bad in [None, 5, b"bytes", ["a"]]:
            self.assertFalse(is_safe_relpath(bad), repr(bad))

    def test_the_ORIGINAL_BASENAME_is_the_leaf_of_every_stored_path(self):
        """This is what makes the repo's existing guards work on mirror paths.

        The draft put the source filename in a DIRECTORY segment and a hash in
        the basename; a real basename-matching read guard returns null for a
        mirrored `.env.local` and `id_rsa` under that shape and the correct
        refusal under this one (executed). Every name-based guard — and a
        sandbox profile's read denies — then work on the mirror unchanged.
        """
        for relpath in ["lib/db.ts", ".env.local", "a/b/c/id_rsa", "top.md"]:
            subpath = version_subpath("repo", "slug", relpath, version_key(1, "a" * 64))
            self.assertEqual(subpath.split("/")[-1], relpath.split("/")[-1], relpath)
            self.assertTrue(subpath.split("/")[-2].startswith("@"), relpath)

    def test_the_version_is_a_DIRECTORY_between_the_path_and_the_leaf(self):
        subpath = version_subpath("repo", "slug", "lib/db.ts", version_key(7, "c" * 64))
        self.assertEqual(subpath, "repo/slug/lib/@%019d-%s/db.ts" % (7, "c" * 12))
        self.assertEqual(path_subpath("repo", "slug", "lib/db.ts"), "repo/slug/lib")

    def test_version_subpath_refuses_an_unsafe_relpath_at_WRITE_time(self):
        for bad in ["../escape", "/abs", "a/../../b", "x\x00y"]:
            with self.assertRaises(ValueError, msg=bad):
                version_subpath("repo", "slug", bad, version_key(1, "a" * 64))

    def test_root_slug_separates_two_roots_that_share_a_basename(self):
        # Review §4.2's layout is `<store>/<root-id>/<relpath>`, which collides:
        # the `worktrees` id globs to many directories and two worktrees both
        # holding `lib/x.ts` would share one version history.
        a = root_slug("worktrees", "/repo/.claude/worktrees/agent-a")
        b = root_slug("worktrees", "/repo/.claude/worktrees/agent-b")
        self.assertNotEqual(a, b)
        same_name = (root_slug("repo", "/one/my-repo"), root_slug("repo", "/two/my-repo"))
        self.assertNotEqual(*same_name)
        self.assertTrue(all(s.startswith("my-repo-") for s in same_name))

    def test_version_key_round_trips_and_sorts_by_capture_time(self):
        early = version_key(1, "a" * 64)
        late = version_key(2 ** 62, "b" * 64)
        self.assertLess(early, late)
        self.assertEqual(parse_version_key(early), (1, "a" * 12))
        self.assertIsNone(parse_version_key("lib"))
        self.assertIsNone(parse_version_key("@123-nothex"))

    def test_version_key_DOES_NOT_TAKE_A_SOURCE_MTIME(self):
        """C12, asserted on the signature rather than on behaviour.

        `touch -t 197001020304 f` backdates a file 20,000 days in one command.
        If the version tag or a retention decision derived from the source
        file's mtime, an agent could make a captured version prunable — a delete
        path into the mirror driven from an agent-writable tree with a coreutil.
        The parameter simply does not exist, which is a stronger statement than
        any test of what the function does with it.
        """
        import inspect
        parameters = list(inspect.signature(version_key).parameters)
        self.assertEqual(parameters, ["capture_epoch_ns", "content_sha256"])
        self.assertNotIn("mtime", " ".join(parameters))


# ── prune_plan (H8) ───────────────────────────────────────────────────────────


class PrunePlanTests(unittest.TestCase):
    """Rows are `(path_dir, leaf, version_key, capture_ns)`; plans are `(path_dir, key)`.

    The population here deliberately puts SEVERAL files in ONE directory. In the
    store layout the version directories of every file in a source directory
    are siblings, and the first shipped `prune_plan` keyed "newest" on the
    directory alone — so it kept one version per directory and would have
    deleted the only copy of every other file in it after 30 days. The earlier
    tests used one file per directory and could not see that: the claim and
    its evidence did not share a population.
    """

    def test_empty_index_yields_an_empty_plan(self):
        self.assertEqual(prune_plan([], now_ns=10 ** 18, window_ns=30 * NS_PER_DAY), [])

    def test_never_prunes_the_newest_version_of_a_relpath(self):
        # H8: a file written 31 days ago and never touched has exactly one
        # version. Naive age-pruning deletes the ONLY copy of the stable files
        # most worth keeping — the guarantee inverts.
        now = 100 * NS_PER_DAY
        rows = [("dirA", "a.md", version_key(1 * NS_PER_DAY, "a" * 64), 1 * NS_PER_DAY)]
        self.assertEqual(prune_plan(rows, now, 30 * NS_PER_DAY), [])

    def test_newest_survives_even_when_every_version_is_ancient(self):
        now = 100 * NS_PER_DAY
        rows = [
            ("dirA", "a.md", version_key(1 * NS_PER_DAY, "a" * 64), 1 * NS_PER_DAY),
            ("dirA", "a.md", version_key(2 * NS_PER_DAY, "b" * 64), 2 * NS_PER_DAY),
            ("dirA", "a.md", version_key(3 * NS_PER_DAY, "c" * 64), 3 * NS_PER_DAY),
        ]
        plan = prune_plan(rows, now, 30 * NS_PER_DAY)
        self.assertEqual(len(plan), 2)
        self.assertNotIn(("dirA", version_key(3 * NS_PER_DAY, "c" * 64)), plan)

    def test_nothing_inside_the_window_is_pruned(self):
        now = 100 * NS_PER_DAY
        rows = [
            ("dirA", "a.md", version_key(80 * NS_PER_DAY, "a" * 64), 80 * NS_PER_DAY),
            ("dirA", "a.md", version_key(90 * NS_PER_DAY, "b" * 64), 90 * NS_PER_DAY),
        ]
        self.assertEqual(prune_plan(rows, now, 30 * NS_PER_DAY), [])

    def test_a_1970_SOURCE_mtime_does_not_make_a_recent_capture_prunable(self):
        """C12 in the prune plan, not just in the version key.

        The row carries a source mtime from 1970 — one `touch -t` away — and a
        capture clock from a minute ago. Only the capture clock is an input, so
        the version is not in the plan. If the prune ever read source mtime, an
        agent could delete its own tracks from the mirror.
        """
        now = 100 * NS_PER_DAY
        ancient_source_mtime = 1 * NS_PER_DAY
        rows = [
            ("dirA", "a.md", version_key(now - NS_PER_DAY, "a" * 64), now - NS_PER_DAY),
            ("dirA", "a.md", version_key(now, "b" * 64), now),
        ]
        plan = prune_plan(rows, now, 30 * NS_PER_DAY)
        self.assertEqual(plan, [], "a recent capture must never be prunable")
        # And the source mtime is not even representable in the row shape.
        self.assertNotIn(ancient_source_mtime, [row[3] for row in rows])

    def test_each_relpath_keeps_its_own_newest(self):
        now = 100 * NS_PER_DAY
        rows = []
        for directory in ("dirA", "dirB"):
            for day in (1, 2):
                rows.append((directory, "f.md", version_key(day * NS_PER_DAY, "a" * 64),
                             day * NS_PER_DAY))
        plan = prune_plan(rows, now, 30 * NS_PER_DAY)
        pruned_dirs = sorted(set(d for d, _ in plan))
        self.assertEqual(pruned_dirs, ["dirA", "dirB"])
        self.assertEqual(len(plan), 2)  # one per path, the older one

    def test_two_files_in_one_directory_each_keep_their_own_newest(self):
        """The case the first shipped version got wrong.

        `a.md` has one ancient version and `b.md` has two, all in the same
        directory. Keyed on the directory, the plan kept b's newest and deleted
        a's ONLY copy. Keyed on the path, a's survives and only b's older goes.
        """
        now = 100 * NS_PER_DAY
        a_only = version_key(1 * NS_PER_DAY, "a" * 64)
        b_old = version_key(2 * NS_PER_DAY, "b" * 64)
        b_new = version_key(3 * NS_PER_DAY, "c" * 64)
        rows = [
            ("dir", "a.md", a_only, 1 * NS_PER_DAY),
            ("dir", "b.md", b_old, 2 * NS_PER_DAY),
            ("dir", "b.md", b_new, 3 * NS_PER_DAY),
        ]
        plan = prune_plan(rows, now, 30 * NS_PER_DAY)
        self.assertEqual(plan, [("dir", b_old)])

    def test_a_stable_file_survives_a_busy_sibling(self):
        """One version of `stable.md`, fifty of `busy.md`, all beyond the window.

        Exactly one version per PATH must survive: the stable file's only copy
        and the busy file's newest. A plan that removed 50 of 51 would have
        kept one per directory.
        """
        now = 100 * NS_PER_DAY
        rows = [("dir", "stable.md", version_key(1 * NS_PER_DAY, "0" * 64), 1 * NS_PER_DAY)]
        for day in range(2, 52):
            rows.append(("dir", "busy.md", version_key(day * NS_PER_DAY, "%064x" % day),
                         day * NS_PER_DAY))
        plan = prune_plan(rows, now, 30 * NS_PER_DAY)
        self.assertEqual(len(plan), 49)
        self.assertNotIn(("dir", rows[0][2]), plan, "the stable file's only copy")
        self.assertNotIn(("dir", rows[-1][2]), plan, "the busy file's newest")

    def test_a_version_directory_with_no_leaf_ages_out_like_any_other(self):
        # A crash between mkdir and link leaves `@key/` empty; its leaf is None.
        now = 100 * NS_PER_DAY
        rows = [
            ("dir", None, version_key(1 * NS_PER_DAY, "a" * 64), 1 * NS_PER_DAY),
            ("dir", None, version_key(2 * NS_PER_DAY, "b" * 64), 2 * NS_PER_DAY),
        ]
        self.assertEqual(prune_plan(rows, now, 30 * NS_PER_DAY),
                         [("dir", version_key(1 * NS_PER_DAY, "a" * 64))])


class StoreNamespaceRelpathTests(unittest.TestCase):
    """`is_safe_relpath` refuses the two shapes the store itself cannot hold."""

    def test_a_component_shaped_like_a_version_key_is_unsafe(self):
        key = version_key(1_700_000_000_000_000_000, "0123456789abcdef")
        for bad in (key, key + "/x.md", "docs/" + key, "docs/" + key + "/notes.md"):
            self.assertFalse(is_safe_relpath(bad), bad)

