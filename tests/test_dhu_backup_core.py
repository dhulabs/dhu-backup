class VersionWindowPlanTests(unittest.TestCase):
    """The per-path cap as a ROLLING WINDOW, not a skip.

    As a skip, `max_versions_per_path` protected the store by dropping exactly
    the newest work on the most actively edited file — the shape the founding
    incident lost. The window drops the OLDEST instead, so the cap still bounds
    a path at `cap x max_file_bytes` while the newest content is always present.
    """

    CAP = 5

    def rows(self, count, start=1):
        # capture clock in the key, deliberately not equal to any source mtime
        return [(version_key(i * 10 ** 9, "%02x" % i * 32), i * 10 ** 9)
                for i in range(start, start + count)]

    def test_below_the_cap_the_plan_is_empty(self):
        for count in range(0, self.CAP):
            self.assertEqual(version_window_plan(self.rows(count), self.CAP), [], count)

    def test_at_or_above_the_cap_it_returns_the_n_minus_cap_plus_one_oldest(self):
        for count in range(self.CAP, self.CAP + 6):
            plan = version_window_plan(self.rows(count), self.CAP)
            self.assertEqual(len(plan), count - self.CAP + 1, count)
            oldest = [key for key, _ in self.rows(count)][: len(plan)]
            self.assertEqual(plan, oldest, count)

    def test_the_room_it_makes_lands_the_new_version_at_exactly_the_cap(self):
        rows = self.rows(self.CAP + 3)
        plan = version_window_plan(rows, self.CAP)
        remaining = len(rows) - len(plan)
        self.assertEqual(remaining + 1, self.CAP)

    def test_the_newest_version_is_never_in_the_plan(self):
        for count in range(1, 40):
            for cap in (1, 2, 3, 5, 200):
                rows = self.rows(count)
                newest = max(rows, key=lambda row: row[1])[0]
                self.assertNotIn(newest, version_window_plan(rows, cap),
                                 "count=%d cap=%d" % (count, cap))

    def test_a_cap_of_one_still_keeps_the_newest(self):
        # The arithmetic alone would ask for every version here; the clamp is
        # what stops a misconfigured cap emptying a path.
        rows = self.rows(4)
        plan = version_window_plan(rows, 1)
        self.assertEqual(len(plan), 3)
        self.assertNotIn(rows[-1][0], plan)

    def test_ordering_is_by_the_CAPTURE_clock_not_by_input_order(self):
        # The daemon lists a directory, which is not ordered by time.
        rows = self.rows(self.CAP + 2)
        shuffled = list(reversed(rows))
        self.assertEqual(version_window_plan(shuffled, self.CAP),
                         version_window_plan(rows, self.CAP))

    def test_a_backdated_SOURCE_mtime_cannot_choose_what_the_window_drops(self):
        """C12 again, in the window this time.

        The rows carry only the capture clock. If the window ordered by source
        mtime, `touch -t 197001020304` before a capture would let an agent make
        one of its own versions the "oldest" and have the daemon delete it.
        """
        rows = self.rows(self.CAP + 1)
        # A row shape carrying a source mtime does not exist; assert the tuple
        # width so a future widening has to come past this test.
        self.assertTrue(all(len(row) == 2 for row in rows))
        # n = cap + 1, so the plan is the two oldest: one to get under the cap
        # and one more to leave room for the incoming version.
        plan = version_window_plan(rows, self.CAP)
        self.assertEqual(plan, [rows[0][0], rows[1][0]])

    def test_an_empty_or_nonsensical_cap_deletes_nothing(self):
        self.assertEqual(version_window_plan([], 5), [])
        self.assertEqual(version_window_plan(self.rows(3), 0), [])
        self.assertEqual(version_window_plan(self.rows(3), -1), [])


